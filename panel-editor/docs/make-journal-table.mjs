// Generates docs/JOURNAL-RULES.md from src/journals.js so the documentation cannot drift from the code.
import { JOURNALS, MM } from '../src/journals.js';
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const here = path.dirname(fileURLToPath(import.meta.url));
const v = (x, u = '') => (x == null ? '—' : x + u);
let md = `# Journal rules built into Panel Editor

> **STATUS: UNVERIFIED.** These numbers come from *web-search summaries* of each journal's author guidelines.
> The journals' own pages could not be opened when this was written (the hosts were blocked), and the
> summaries contradict each other in places (see "Conflicting values"). **Check every value against the
> journal's current instructions before submitting**, fix it in *Edit rules…*, then tick *I checked these*.
> Generated by \`node docs/make-journal-table.mjs\` — do not edit by hand.

`;
for (const k of ['nature', 'cell', 'science']) {
  const r = JOURNALS[k];
  md += `## ${r.name}\n\n| Rule | Value used | Source |\n|---|---|---|\n`;
  md += `| Figure widths (single / 1.5 / double) | ${v(r.widthsMm.single)} / ${v(r.widthsMm.onehalf)} / ${v(r.widthsMm.double)} mm (${(r.widthsMm.single * MM).toFixed(1)} / ${(r.widthsMm.onehalf * MM).toFixed(1)} / ${(r.widthsMm.double * MM).toFixed(1)} pt) | ${r.sources.widths} |\n`;
  md += `| Maximum height | ${v(r.maxHeightMm, ' mm')} | ${r.sources.maxHeight} |\n`;
  md += `| Panel letters | ${r.letter.case === 'upper' ? 'capital' : 'lowercase'}, ${r.letter.bold ? 'bold' : 'regular'}, ${r.letter.size} pt | ${r.sources.letter} |\n`;
  md += `| Text size | ${v(r.text.minPt)}–${v(r.text.maxPt)} pt | ${r.sources.text} |\n`;
  md += `| Minimum line weight | ${v(r.minLinePt, ' pt')} | ${r.sources.minLine} |\n`;
  md += `| Figure names (main / supp. / extended) | “${r.names.main}1” / “${r.names.supp}1” / “${r.names.ed}1” | ${r.sources.names} |\n\n`;
  if (r.alt.length) md += `**Conflicting or alternative values found:**\n\n${r.alt.map((a) => `- ${a}`).join('\n')}\n\n`;
  if (r.notes.length) md += r.notes.map((n) => `> ${n}`).join('\n') + '\n\n';
}
md += `## What the app does with these\n\n- **Switch journal…** restyles the whole project (artboard width, artwork scale, letter style, naming, text-size range, grid).\n- **Check rules** lists widths, heights, text sizes, line weights, letter style, overlaps and panels outside the artboard.\n- Values you edit are stored in the file (\`settings.journalOverrides\`) and travel with it.\n`;
fs.writeFileSync(path.join(here, 'JOURNAL-RULES.md'), md); console.log('wrote docs/JOURNAL-RULES.md');
